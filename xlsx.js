// Δέχεται: { sheets: [{ name, rows: [[cell, ...]], widths: [..], freeze: n, active }] }
// cell: null | αριθμός | κείμενο | { v, s } με s = 'head' | 'money' | 'moneyB' | 'bold' | 'title' | 'date' | 'num' | 'pct' | 'sub' | 'moneyR' | 'moneyG'
const zlib = require('zlib');

const STYLE = { head: 1, money: 2, moneyB: 3, bold: 4, title: 5, date: 6, num: 7, pct: 8, sub: 9, moneyR: 10, moneyG: 11, totalTxt: 12 };

function esc(s) {
  return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
}
function colName(i) { let s = ''; i++; while (i > 0) { const m = (i - 1) % 26; s = String.fromCharCode(65 + m) + s; i = Math.floor((i - 1) / 26); } return s; }
function sheetName(n, used) {
  let s = String(n).replace(/[\\/?*[\]:]/g, ' ').slice(0, 31).trim() || 'Φύλλο';
  let k = 2, base = s;
  while (used.has(s)) s = (base.slice(0, 28) + ' ' + k++);
  used.add(s); return s;
}

function sheetXml(sh) {
  const rows = sh.rows || [];
  const cols = (sh.widths || []).map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const pane = sh.freeze ? `<pane ySplit="${sh.freeze}" topLeftCell="A${sh.freeze + 1}" activePane="bottomLeft" state="frozen"/>` : '';
  let body = '';
  rows.forEach((row, r) => {
    let cells = '';
    (row || []).forEach((c, i) => {
      if (c === null || c === undefined || c === '') return;
      const o = typeof c === 'object' ? c : { v: c };
      if (o.v === null || o.v === undefined || o.v === '') { if (o.s) cells += `<c r="${colName(i)}${r + 1}" s="${STYLE[o.s] || 0}"/>`; return; }
      const ref = `${colName(i)}${r + 1}`, s = o.s ? ` s="${STYLE[o.s] || 0}"` : '';
      if (typeof o.v === 'number' && isFinite(o.v)) cells += `<c r="${ref}"${s}><v>${Math.round(o.v * 100) / 100 === o.v ? o.v : +o.v.toFixed(6)}</v></c>`;
      else if (typeof o.f === 'string') cells += `<c r="${ref}"${s}><f>${esc(o.f)}</f></c>`;
      else cells += `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(o.v)}</t></is></c>`;
    });
    const ht = row && row.height ? ` ht="${row.height}" customHeight="1"` : '';
    body += `<row r="${r + 1}"${ht}>${cells}</row>`;
  });
  const merges = (sh.merges || []).length ? `<mergeCells count="${sh.merges.length}">${sh.merges.map(m => `<mergeCell ref="${m}"/>`).join('')}</mergeCells>` : '';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetPr><pageSetUpPr fitToPage="1"/></sheetPr>
<sheetViews><sheetView workbookViewId="0" zoomScale="110"${sh.active ? ' tabSelected="1"' : ''}>${pane}</sheetView></sheetViews>
<sheetFormatPr defaultRowHeight="18"/>
${cols ? `<cols>${cols}</cols>` : ''}
<sheetData>${body}</sheetData>${merges}
<pageMargins left="0.5" right="0.5" top="0.6" bottom="0.6" header="0.3" footer="0.3"/>
<pageSetup paperSize="9" orientation="${sh.landscape ? 'landscape' : 'portrait'}" fitToWidth="1" fitToHeight="0"/>
</worksheet>`;
}

